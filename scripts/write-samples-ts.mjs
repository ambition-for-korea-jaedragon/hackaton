// Regenerate src/lib/samples.ts from the demo sample definitions + the e2e fixtures.
import { writeFileSync, readdirSync } from "node:fs";
import { LOOKS, SELFIES } from "./demo-sample-defs.mjs";
const title = (id) => id.split("-").map((w) => w[0].toUpperCase() + w.slice(1)).join(" ");
const items = (list, dir, prefix) => list.map(([id, name]) => ({ id, name, src: `/samples/${prefix}${id}.jpg` }));
const testLooks = readdirSync("public/e2e").filter((f) => f.startsWith("look-")).map((f) => { const id = f.slice(5, -4); return { id, name: title(id), src: `/e2e/${f}` }; });
const testSelfies = readdirSync("public/e2e").filter((f) => f.startsWith("selfie-")).map((f) => { const id = f.slice(7, -4); return { id, name: title(id), src: `/e2e/${f}` }; });
const out = `// GENERATED by scripts/write-samples-ts.mjs. All photos are AI-generated, fictional people.
export type SampleItem = { id: string; name: string; src: string };

// Demo looks: pre-filled (analysis, hashtags, mannequin, muse products are prepared ahead of time).
export const SAMPLES: SampleItem[] = ${JSON.stringify(items(LOOKS, "samples", "muse-"), null, 2)};

// Demo selfies: dragging one onto the selfie box runs the real application (image generation).
export const SELFIES: SampleItem[] = ${JSON.stringify(items(SELFIES, "samples", "me-"), null, 2)};

// E2E test looks: used as real uploads, so they are analyzed live (no prepared data).
export const TEST_LOOKS: SampleItem[] = ${JSON.stringify(testLooks, null, 2)};

// E2E test selfies: real application as well.
export const TEST_SELFIES: SampleItem[] = ${JSON.stringify(testSelfies, null, 2)};
`;
writeFileSync("src/lib/samples.ts", out);
console.log("looks", LOOKS.length, "selfies", SELFIES.length, "test looks", testLooks.length, "test selfies", testSelfies.length);
