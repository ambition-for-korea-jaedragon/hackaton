import { chromium } from "playwright-core";
const exe = process.env.HOME + "/Library/Caches/ms-playwright/chromium-1208/chrome-mac-arm64/Google Chrome for Testing.app/Contents/MacOS/Google Chrome for Testing";
const browser = await chromium.launch({ executablePath: exe, headless: true, args: ["--use-gl=angle", "--use-angle=swiftshader", "--enable-unsafe-swiftshader", "--no-sandbox"] });
const ctx = await browser.newContext({ viewport: { width: 430, height: 900 }, deviceScaleFactor: 1 });
const page = await ctx.newPage();
const errs = [];
page.on("pageerror", (e) => errs.push("pageerror: " + e.message));
page.on("console", (m) => { if (m.type() === "error") errs.push("console: " + m.text()); });
const shot = (n) => page.screenshot({ path: `/tmp/pw/${n}.png` });
const log = (...a) => console.log(new Date().toISOString().slice(11, 19), ...a);
const B = "http://localhost:3100";
try {
  await page.goto(B + "/", { waitUntil: "networkidle" });
  await page.getByRole("link", { name: "Make a new look" }).click();
  await page.waitForURL("**/new"); log("on /new"); await shot("1-new");
  await page.getByRole("radio", { name: /Brick sunset/ }).click();
  await page.getByRole("button", { name: /Analyze This Look/ }).click();
  await page.waitForURL("**/s/**", { timeout: 60000 }); log("analysis done →", page.url());
  await page.waitForSelector("text=See It On Me", { timeout: 20000 }); await shot("2-breakdown");
  await page.getByRole("button", { name: /See It On Me/ }).click(); await shot("3-onme-empty");
  await page.setInputFiles('input[type="file"]', "/Users/choam2426/workspace/hackaton/public/e2e/selfie-tan-warm.jpg");
  await page.getByRole("checkbox").check();
  await shot("4-selfie-ready");
  await page.getByRole("button", { name: /Translate To My Tone/ }).click(); log("selfie sent, translating");
  await page.waitForSelector("text=Share My Look", { timeout: 20000 });
  await page.waitForFunction(() => { const b = [...document.querySelectorAll("button")].find((x) => /Share My Look/.test(x.textContent || "")); return b && !b.disabled; }, null, { timeout: 180000 });
  log("③ + styled done"); await shot("6-mytone");
  await page.getByRole("button", { name: /Share My Look/ }).click(); await shot("7-share");
  await page.getByRole("textbox").first().fill("Brick sunset, tan edition");
  await page.getByRole("button", { name: /Post to Feed/ }).click();
  await page.waitForSelector("text=Copy link", { timeout: 20000 }); log("posted"); await shot("8-posted");
  await page.goto(B + "/", { waitUntil: "networkidle" }); await page.waitForTimeout(1500); await shot("9-feed");
} catch (e) { log("FAIL", e.message.split("\n")[0]); await shot("fail"); }
console.log("errors:", errs.slice(0, 8));
await browser.close();
